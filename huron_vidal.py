def _kij_hv(eos):
    import eos as _e
    return np.array(KIJHV_SRK if _e.es_srk(eos) else KIJHV_PR)


def _g_matrix_delta0(eos):
    import eos as _e
    return np.array(G0_SRK if _e.es_srk(eos) else G0_PR)


def _g_matrix_deltaT(eos):
    import eos as _e
    return np.array(GT_SRK if _e.es_srk(eos) else GT_PR)


def hay_agua(z, tol=1e-12):
    z = np.asarray(z, dtype=float)
    return len(z) > IDX_AGUA and z[IDX_AGUA] > tol


def _lambda_eos(eos):
    """lambda de la regla H&V especifico de la EOS (manual PVTsim).
    SRK: lambda = ln2.  PR: lambda = (1/(2 sqrt2))*ln((1+sqrt2)/(sqrt2-1))."""
    import eos as _e
    if _e.es_srk(eos):
        return np.log(2.0)
    return (1.0/(2.0*np.sqrt(2.0)))*np.log((1.0+np.sqrt(2.0))/(np.sqrt(2.0)-1.0))


_TAU_CACHE = {}

def _tau_alpha(eos, T_R, aa, bi, kij_classic):
    """(tau, alpha) de Huron-Vidal. Cacheado por (eos, T_R redondeada) — no
    dependen de la composición, así que se calculan una sola vez por T."""
    key = (eos, round(T_R, 4), round(float(aa[0]), 6), round(float(bi[0]), 6))
    c = _TAU_CACHE.get(key)
    if c is not None:
        return c
    N = len(bi)
    import eos as _e
    T_K = T_R/1.8
    G0 = _g_matrix_delta0(eos)
    GT = _g_matrix_deltaT(eos)
    kijhv = _kij_hv(eos)
    ALPHA = np.array(ALPHA_SRK if _e.es_srk(eos) else ALPHA_PR)
    kij_ag = KIJ_AGUA_CLASSIC_SRK if _e.es_srk(eos) else KIJ_AGUA_CLASSIC_PR
    # Formulación EXACTA de Pedersen (2024), cap. 16, ec. 16.10-16.13:
    #   G^E/RT = Σ_i z_i · [Σ_j τ_ji b_j z_j exp(-α_ji τ_ji)] / [Σ_k b_k z_k exp(-α_ki τ_ki)]
    #   τ_ji = (g_ji - g_ii)/(R T)      (ec. 16.2 vía 16.10)
    #   g_ii = -a_i/b_i                 (ec. 16.12)  ← SIN λ (el λ solo aparece en
    #                                    la conversión a↔G^E, no en g_ii)
    #   g_ji (HC-HC) = (2 b_i b_j/(b_i+b_j))·(-√(g_ii g_jj))·(1-k_ij)  (ec. 16.13),
    #     que da τ_ji = (g_ji-g_ii)/(RT) reproduciendo la regla clásica.
    # Para pares agua-HC(HV), (g_ji-g_ii)/R viene de las matrices del Excel
    # "HV g/R (K)" (G0) y "HV g-T/R" (GT) con dependencia lineal en T (ec.
    # 16.19-16.20), T de referencia 0 K (T absoluta):  τ_ji = (G0 + GT·T_K)/T_K.
    # g_ii para los pares CLÁSICOS dentro de HV (HC-HC y agua-pesados).  El
    # manual de PVTsim (Equations of State, regla H&V) da g_ii = a_i/(b_i·λ) y,
    # con esa forma, la regla H&V se reduce EXACTAMENTE a la cuadrática clásica
    # cuando α=0.  Verificado numéricamente: sin el factor λ, a_m(HV) difería de
    # a_m(clásica) en 0.16 % para una mezcla HC pura (el factor que restaura la
    # identidad es exactamente λ).  Los pares agua-HV NO usan g_ii (su τ viene de
    # las matrices G0/GT del Excel), así que este factor no los afecta.
    lam = _lambda_eos(eos)
    gii = -(aa/bi)*lam                 # g_ii = -a_i·λ/b_i (reduce HV→clásica exacto)
    tau = np.zeros((N, N)); alpha = np.zeros((N, N))
    for i in range(N):
        for j in range(N):
            if i == j:
                continue
            # ¿es un par agua-HC que PVTsim trata con Huron-Vidal?
            hc = j if i == IDX_AGUA else (i if j == IDX_AGUA else None)
            if hc is not None and hc in HV_AGUA_IDX:
                # Par agua-HC (HV).  G0 = (g_ji-g_ii)/R en K; GT adimensional.
                #   τ_ji = (g_ji - g_ii)/(R·T) = [(g_ji-g_ii)/R]/T_K = (G0+GT·T_K)/T_K
                tau[j, i] = (G0[j, i] + GT[j, i]*T_K)/T_K
                alpha[j, i] = ALPHA[j, i]          # no-aleatoriedad NRTL (ec. 16.10)
            elif hc is not None:
                # Par agua-HC pesado (nC6..nC9): regla CLÁSICA (α=0) con kij agua.
                fac = 2.0*np.sqrt(bi[i]*bi[j])/(bi[i]+bi[j])
                kij_w = kij_ag[hc]
                g_ji = -fac*np.sqrt(gii[i]*gii[j])*(1.0 - kij_w)
                tau[j, i] = (g_ji - gii[i])/(R_GAS*T_R)
            else:
                # Par HC-HC: regla clásica (α=0) con kij HC-HC (ec. 16.13).
                fac = 2.0*np.sqrt(bi[i]*bi[j])/(bi[i]+bi[j])
                g_ji = -fac*np.sqrt(gii[i]*gii[j])*(1.0 - kij_classic[i, j])
                tau[j, i] = (g_ji - gii[i])/(R_GAS*T_R)
    E = np.exp(-np.clip(alpha*tau, -300, 300))
    TE = tau*E                       # τ_ji·exp(-α_ji τ_ji)
    _TAU_CACHE[key] = (tau, alpha, E, TE)
    if len(_TAU_CACHE) > 200:        # evitar crecimiento ilimitado
        _TAU_CACHE.clear(); _TAU_CACHE[key] = (tau, alpha, E, TE)
    return _TAU_CACHE[key]


def am_bm_hv(z, aa, bi, eos, T_R, kij_classic):
    """a_m y b_m por Huron-Vidal (manual PVTsim). Ver también qbar_hv para la
    derivada usada en la fugacidad."""
    am, bm, _ = _am_qbar_hv(z, aa, bi, eos, T_R, kij_classic, con_qbar=False)
    return am, bm


def _am_qbar_hv(z, aa, bi, eos, T_R, kij_classic, con_qbar=True):
    """Devuelve (am, bm, qbar) donde qbar_i = (1/am)·∂(n²am)/∂n_i evaluado a n=1
    (composición z normalizada). qbar entra en ln φ_i como el término 2·sum_aij/am.

    Derivada analítica de la regla H&V:
        am = bm·[ Σ_k z_k (a_k/b_k) − G^E/λ ]
    con G^E/RT = Σ_i z_i · S_i,  S_i = num_i/den_i,
        num_i = Σ_j τ_ji b_j z_j E_ji,   den_i = Σ_k b_k z_k E_ki,  E=exp(-ατ).
    """
    z = np.asarray(z, dtype=float)
    N = len(z)
    bm = float(z @ bi)
    lam = _lambda_eos(eos)
    tau, alpha, E, TE = _tau_alpha(eos, T_R, aa, bi, kij_classic)

    bz = bi*z
    den = E.T @ bz                       # den_i = Σ_k b_k z_k E_ki  (vector N)
    den = np.where(np.abs(den) < 1e-300, 1e-300, den)
    num = TE.T @ bz                      # num_i = Σ_j τ_ji b_j z_j E_ji
    S = num/den                          # S_i
    GE_RT = float(z @ S)
    GE = GE_RT*R_GAS*T_R
    aob = aa/bi
    suma = float(z @ aob)
    am = bm*(suma - GE/lam)

    if not con_qbar:
        return am, bm, None

    # ∂(n²am)/∂n_i a n=1. Con n²am = (Σz b)·(Σz a/b − G^E/λ)·... cuidado:
    # trabajamos con cantidades molares. am(z) es intensivo; n²am con n=1 = am.
    # ∂(n²am)/∂n_i = 2·am·(algo). Usamos la forma estándar:
    #   ∂(n·am_molar)/∂n_i evaluada a n=1 da: am + n·∂am/∂n_i.
    # Para la fugacidad se necesita qbar_i tal que el término sea:
    #   (1/am)·[ ∂(n² am)/∂n_i ].
    # ∂(n² am)/∂n_i = 2 b_i (suma - G^E/λ)         [de ∂bm]
    #                + 2 bm ( a_i/b_i·? )           [de ∂suma]  -- ver abajo
    # Derivación term a term (todas evaluadas a n=1, z=comp):
    # Sea F = suma - GE_RT·RT/λ.  am = bm·F.
    # ∂(n²am)/∂n_i = ∂(N_tot·bmpartial ...). Usamos resultado conocido:
    #   qbar_i = (1/am)·[ 2 b_i F + 2 bm (aob_i - dGE_dn_i/λ) ]  ... (a n=1)
    # donde dGE_dn_i = ∂(n·G^E_RT·RT)/∂n_i.
    RT = R_GAS*T_R
    # ∂(n G^E_RT)/∂n_i con G^E_RT = Σ_i z_i S_i:
    #   = S_i  +  Σ_k z_k ∂S_k/∂n_i
    # ∂S_k/∂n_i = ∂(num_k/den_k)/∂n_i
    #   num_k = Σ_j τ_jk b_j z_j E_jk ;  ∂num_k/∂z_i = τ_ik b_i E_ik
    #   den_k = Σ_j b_j z_j E_jk ;       ∂den_k/∂z_i = b_i E_ik
    # a n=1, ∂/∂n_i = ∂/∂z_i - (proyección), pero para qbar usamos la forma
    # con derivadas respecto a moles n_i (Gibbs). Empleamos:
    dnum = (TE * bi.reshape(N,1))        # dnum[i,k] = τ_ik b_i E_ik = ∂num_k/∂z_i
    dden = (E * bi.reshape(N,1))         # dden[i,k] = b_i E_ik = ∂den_k/∂z_i
    dS = (dnum - (S.reshape(1,N))*dden)/den.reshape(1,N)   # ∂S_k/∂z_i  (i filas,k col)
    dGE_RT_dn = S + dS @ z               # ∂(Σ z_k S_k)/∂n_i  (a n=1)
    dGE_dn = dGE_RT_dn*RT
    F = suma - GE/lam
    # sum_aij_i = b_i·F + bm·(aob_i − dGE_dn_i/λ)   (validado vs numérica)
    dn2am = bi*F + bm*(aob - dGE_dn/lam)
    qbar = 2.0*dn2am/am           # qbar tal que sum_aij = am·qbar/2 = dn2am
    return am, bm, qbar
